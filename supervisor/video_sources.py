"""Safe logical-video resolution for legacy and managed Supervisor sources.

Existing API fields still call this value ``filename`` for compatibility, but
they now accept a logical video reference: either a legacy input filename or a
managed-original VideoAsset id.  No caller supplies a filesystem path.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any

from supervisor.media_library import MediaLibrary, MediaLibraryNotFoundError


class VideoSourceError(ValueError):
    """Base error for an invalid logical video reference."""


class VideoSourceNotFoundError(VideoSourceError):
    """The requested logical video reference is not available."""


class VideoSourceUnsupportedError(VideoSourceError):
    """The asset exists but cannot yet be used as a calibration source."""


def _safe_key(value: str, fallback: str = "video") -> str:
    safe = "".join(character if character.isalnum() or character in "-_" else "_" for character in value)
    return safe or fallback


@dataclass(frozen=True)
class VideoSource:
    """One safe, stable source behind legacy ``filename`` API fields."""

    reference: str
    source_type: str
    path: Path
    review_key: str
    result_key: str
    display_name: str
    asset_id: str | None = None
    legacy_filename: str | None = None
    original_filename: str | None = None
    technical: dict[str, Any] | None = None

    def review_path(self, review_dir: Path) -> Path:
        """Return the controlled, per-source review location."""

        return Path(review_dir) / f"{self.review_key}.json"

    def result_basename(self, suffix: str) -> str:
        """Build a deterministic basename for a per-source derived result."""

        if not isinstance(suffix, str) or not suffix:
            raise VideoSourceError("Result suffix is required")
        return f"{self.result_key}{suffix}"


def _legacy_source(reference: str, input_dir: Path) -> VideoSource | None:
    if not isinstance(reference, str) or not reference:
        return None
    candidate = Path(reference)
    if candidate.name != reference or candidate.suffix.lower() != ".mp4":
        return None
    root = Path(input_dir).resolve()
    path = (root / candidate.name).resolve()
    if path.parent != root or not path.is_file():
        return None
    key = _safe_key(path.stem, "review")
    return VideoSource(
        reference=reference,
        source_type="legacy_input",
        path=path,
        review_key=key,
        result_key=key,
        display_name=path.stem,
        legacy_filename=path.name,
    )


def resolve_video_source(
    reference: str,
    *,
    library: MediaLibrary,
    input_dir: Path,
) -> VideoSource:
    """Resolve a safe legacy filename or managed-original asset id.

    ``segment_derived`` remains intentionally unsupported for workspace and CV
    operations: its source-video frame indices are not its own timeline.
    """

    legacy = _legacy_source(reference, input_dir)
    if legacy is not None:
        return legacy
    if not isinstance(reference, str) or not reference or Path(reference).name != reference:
        raise VideoSourceNotFoundError("Video source not found")

    try:
        asset = library.get_asset(reference)
    except MediaLibraryNotFoundError as error:
        raise VideoSourceNotFoundError("Video source not found") from error

    storage_type = asset.get("storage_type")
    if storage_type == "segment_derived":
        raise VideoSourceUnsupportedError(
            "Derived segments are not yet supported as calibration/workspace video sources"
        )
    if storage_type not in {"legacy_input", "managed_original"}:
        raise VideoSourceUnsupportedError("Video asset is not a supported workspace source")

    try:
        path = library.resolve_original_asset_path(reference)
    except MediaLibraryNotFoundError as error:
        raise VideoSourceNotFoundError("Managed video source not found") from error
    expected_root = library.input_dir if storage_type == "legacy_input" else library.managed_videos_dir
    if path.parent != expected_root:
        raise VideoSourceError("Video source is outside its controlled directory")

    if storage_type == "legacy_input":
        # A registered legacy asset keeps the exact historical review/result
        # identity of its input filename while the frontend may use its asset id.
        key = _safe_key(path.stem, "review")
        return VideoSource(
            reference=reference,
            source_type="legacy_input",
            path=path,
            review_key=key,
            result_key=key,
            display_name=str(asset.get("display_name") or path.stem),
            asset_id=reference,
            legacy_filename=path.name,
            technical=asset.get("technical") if isinstance(asset.get("technical"), dict) else None,
        )

    # Asset ids are generated by the server catalog and are the durable review
    # and result identity; physical upload names and display metadata may vary.
    key = _safe_key(reference, "asset")
    return VideoSource(
        reference=reference,
        source_type="managed_original",
        path=path,
        review_key=key,
        result_key=key,
        display_name=str(asset.get("display_name") or reference),
        asset_id=reference,
        original_filename=asset.get("original_filename") if isinstance(asset.get("original_filename"), str) else None,
        technical=asset.get("technical") if isinstance(asset.get("technical"), dict) else None,
    )
